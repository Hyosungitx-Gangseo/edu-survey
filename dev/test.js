// node dev/test.js - Code.gs 동작 확인
const fs = require('fs');
const assert = require('assert');
const { loadGas } = require('./gas-shim.js');
const mem = {}; const storage = { getItem: k => mem[k] ?? null, setItem: (k, v) => { mem[k] = String(v); } };
const call = loadGas(fs.readFileSync(__dirname + '/../apps-script/Code.gs', 'utf8'), storage, { ADMIN_ID: 'admin', ADMIN_PASSWORD: 'pw' });
const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Seoul' }).format(new Date());
const add = (d, n) => { const x = new Date(d + 'T00:00:00Z'); x.setUTCDate(x.getUTCDate() + n); return x.toISOString().slice(0, 10); };

assert.strictEqual(call({ action: 'active' }).survey, null);
assert.ok(!call({ action: 'login', id: 'admin', pw: 'x' }).ok);
assert.ok(!call({ action: 'listSurveys', token: 'bad' }).ok);
const token = call({ action: 'login', id: 'admin', pw: 'pw' }).token;
assert.ok(token);
const old = call({ action: 'saveSurvey', token, title: '지난 회차', start: add(today, -10), end: add(today, -9) });
assert.ok(old.ok);
const cur = call({ action: 'saveSurvey', token, title: '이번 회차', start: today, end: add(today, 1) });
assert.ok(cur.ok, JSON.stringify(cur));
// 기간이 겹치는 설문도 등록 가능, 진행 중인 설문은 목록으로
const second = call({ action: 'saveSurvey', token, title: '겹침', start: today, end: add(today, 2) });
assert.ok(second.ok, JSON.stringify(second));
const act = call({ action: 'active' });
assert.deepStrictEqual(act.surveys.map(s => s.id).sort(), [cur.id, second.id].sort());
assert.strictEqual(call({ action: 'active', id: old.id }).target.state, 'closed');
assert.strictEqual(call({ action: 'active', id: second.id }).target.state, 'active');
assert.strictEqual(call({ action: 'active', id: 'nope' }).target, null);
// 조기 마감 / 마감 취소
assert.ok(call({ action: 'closeSurvey', token, id: second.id }).ok);
assert.deepStrictEqual(call({ action: 'active' }).surveys.map(s => s.id), [cur.id]);
assert.strictEqual(call({ action: 'active', id: second.id }).target.state, 'closed');
assert.strictEqual(call({ action: 'active', id: second.id }).target.closedEarly, true);
assert.ok(/마감/.test(call({ action: 'submit', surveyId: second.id, answers: { ratings: [3,3,3,3,3], issues: ['기타'] } }).error));
assert.strictEqual(call({ action: 'listSurveys', token }).surveys.find(s => s.id === second.id).closedAt, today);
assert.ok(call({ action: 'closeSurvey', token, id: second.id, reopen: true }).ok);
assert.strictEqual(call({ action: 'active', id: second.id }).target.state, 'active');
assert.ok(!call({ action: 'closeSurvey', token, id: old.id, reopen: true }).ok, 'cannot reopen past end');
assert.ok(!call({ action: 'closeSurvey', token: 'bad', id: second.id }).ok);
assert.ok(call({ action: 'deleteSurvey', token, id: second.id }).ok);
assert.strictEqual(call({ action: 'active' }).survey.id, cur.id);
assert.ok(!call({ action: 'submit', surveyId: old.id, answers: { ratings: [1,2,3,4,5], issues: ['기타'] } }).ok, 'closed');
assert.ok(!call({ action: 'submit', surveyId: cur.id, answers: { ratings: [1,2,3,4], issues: ['기타'] } }).ok);
assert.ok(!call({ action: 'submit', surveyId: cur.id, answers: { ratings: [1,2,3,4,5], issues: ['기타', '특별히 없음'] } }).ok);
assert.ok(call({ action: 'submit', surveyId: cur.id, answers: { ratings: [5,4,3,2,1], issues: ['기타', '실무와 맞지 않는 내용'], useful: '사례 분석', issueDetail: '=SUM(A1)', improve: '- 실습 위주', wish: '' } }).ok);
assert.ok(call({ action: 'submit', surveyId: cur.id, answers: { ratings: [3,3,3,3,3], issues: ['특별히 없음'] } }).ok);
const r = call({ action: 'results', token, id: cur.id });
assert.strictEqual(r.count, 2);
assert.strictEqual(r.areas[0].average, 4);
assert.deepStrictEqual(r.areas[0].dist, [1, 0, 1, 0, 0]);
assert.strictEqual(r.issues.find(i => i.name === '기타').count, 1);
assert.deepStrictEqual(r.texts.issueDetail, ['=SUM(A1)']);
assert.deepStrictEqual(r.texts.improve, ['- 실습 위주']);
assert.deepStrictEqual(r.texts.useful, ['사례 분석']);
const list = call({ action: 'listSurveys', token });
assert.strictEqual(list.surveys.length, 2);
assert.strictEqual(list.surveys[1].count, 2);
assert.ok(call({ action: 'deleteSurvey', token, id: cur.id }).ok);
assert.strictEqual(call({ action: 'listSurveys', token }).surveys.length, 1);
for (let i = 0; i < 5; i++) call({ action: 'login', id: 'admin', pw: 'no' });
assert.ok(/너무 많습니다/.test(call({ action: 'login', id: 'admin', pw: 'pw' }).error));
console.log('all tests passed');
